"""
急诊高峰期分诊仲裁器（纯 Python 标准库，单文件）

================================ 设计说明 =================================

1) 分诊级别定义（参照国内急诊预检分诊 I–IV 级）
   L1 濒危：优先级 1，处置时限  0 分钟（立即处置）
   L2 危重：优先级 2，处置时限 10 分钟
   L3 急症：优先级 3，处置时限 30 分钟
   L4 非急：优先级 4，处置时限 120 分钟

2) 分级判定规则（症状与体征“取最高危级”，不能因为主诉轻微就掩盖异常体征）
   - 症状：按 L1→L2→L3 关键词命中，未命中归 L4。
       L1：心脏骤停/无脉/昏迷/意识丧失/意识改变/抽搐/呼吸困难/窒息/大出血/休克 ...
       L2：胸痛/胸闷/中风/偏瘫/剧烈腹痛/呕血/黑便/严重过敏/喉头水肿/喘憋/紫绀 ...
       L3：腹痛/发热/哮喘/呕吐/腹泻/孕妇/阴道出血/头部外伤/骨折/脱水 ...
   - 生命体征硬判据（任一命中即定级）：
       意识=昏迷/意识丧失        -> L1；昏睡 -> L2；嗜睡 -> L3
       SpO2 <90%                 -> L1；90~93 -> L2；94~95 -> L3
       收缩压 <70 / >=200        -> L1；70~89 / >=180 -> L2
       舒张压 >=110              -> L2
       心率 <40 / >150           -> L1；110~130 或 40~50 -> L3；130~150 -> L2
       呼吸 <8 / >30             -> L1；24~30 -> L2
       体温 >=41 或 <=35         -> L2；39~40.9 -> L3
   - 体征字段：conscious / spo2 / sbp / dbp / hr / rr / temp，缺失字段不参与判定。

3) 容量配置（示例：总数 10，分级 1/2/3/3 + 缓冲床 1）
   理由：急诊需求天然呈“金字塔”，濒危位少但必须随时可腾空；L3/L4 区承担
   大部分流量；另设 1 张全院机动缓冲床，只在高峰期被高级别患者临时征用。

4) 容量已满时的处置（“临床级别不降级，床位标签可跨区”，患者安全优先）
   a. 先把“本区里被更低级别患者跨占”的床收回（驱逐该低级别患者回候诊）；
   b. 本区仍无床，则到更低级别区域 / 缓冲床找空床（降级“安置”，不是降级
      “诊疗”，患者仍按原级别计时与处置）；
   c. 再无空床，则从更低级别区域 / 缓冲床驱逐“临床级别最低、到达最晚”且
      尚未处置的患者，腾出床位；
   d. 都不行 -> 进入候床队列（急诊不拒诊），继续按原级别计算处置时限并照
      常报告超时；任何情况下高级别患者不会被低级别患者抢床。
   被驱逐者回到候床队列；有患者离院释放床位时，队列按 (优先级, 到达时间)
   重新分配，且低级别患者不会被“提升”占用高级区空床（优先回本区）。

5) 重复分诊 / 再诊（状态延续）
   - 患者已有“未离院”就诊段时再次 ARRIVE -> 错误 ERR_DUPLICATE_ARRIVAL，
     该事件被忽略（不生成新就诊段）。
   - 已离院后再次 ARRIVE -> 记为“再诊”，生成新就诊段，处置时限重新起算，
     历史就诊段在患者档案中延续可查。

6) 超时未处置
   每个事件处理前扫描：当前时间 - 到达时间 > 本级时限，且尚未 TREAT（在床
   或候床都算）-> 报告 OVERDUE（患者、级别、到达时间、时限、当前时间、超出
   分钟数），每就诊段只报一次；TREAT 后停止计时。

7) 患者引用不存在
   TREAT / DISPOSE 引用了从未出现的患者，或其没有在院就诊段
   -> 错误 ERR_UNKNOWN_PATIENT；对“存在但仍在候床”的患者执行 TREAT
   -> 错误 ERR_INVALID_STATE（尚未入床不能处置）。

8) 输入：事件流，时间单位为分钟（相对时间）；事件类型
   ARRIVE（patient_id/symptoms/vitals）、TREAT（patient_id）、DISPOSE（patient_id）。

直接运行：  python3 triage.py            # 内置示例
自检断言：  python3 triage.py --selftest
===========================================================================
"""

